#!/usr/bin/env node
/** Deterministic CI guard for the single cumulative LUMIA ASUS QA tree. */
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {fileURLToPath} from 'node:url'
const read=p=>readFileSync(fileURLToPath(new URL('../'+p,import.meta.url)),'utf8')
const app=read('src/App.tsx')
const pilot=read('INICIAR_LUMIA_ASUS_NEXT_QA.cmd')
const vision=read('INICIAR_LUMIA_ASUS_VISION_AUDITORIA_VI041.cmd')
const daily=read('INICIAR_LUMIA_ASUS_RAPIDA.cmd')
const voice=read('scripts/lumia-next-local-voice-qa.mjs')
const parser=read('src/scene/lumia-motion-r8/avatar-presence-ph04.ts')
const face=read('src/scene/LumiaPortalHead.tsx')
const vm=read('src/ui/LumiaCameraViewfinder.tsx')
const manifest=JSON.parse(read('LUMIA_NEXT_MANIFEST.json'))

assert.equal(manifest.canonical_integration_branch,'integration/lumia-asus-next-20261114')
assert.equal(manifest.protected_original.expected_commit,'1580a5182eba540893e35e37065be77da4ed014c')
assert.equal(manifest.protected_original.modified_by_integration,false)
assert.ok(manifest.carried_forward.some(x=>x.module==='VQ-05.1' && /visually approved/.test(x.qa)))
assert.ok(manifest.carried_forward.some(x=>x.module==='VI-04.1' && /pending/.test(x.qa)))
assert.equal(manifest.runtime.camera_auto_open,false)
assert.equal(manifest.runtime.facial_identity_enabled,false)
assert.match(pilot,/VITE_LUMIA_NATURAL_FACE_VQ04=1/)
assert.match(pilot,/VITE_LUMIA_SPEECH_EXPRESSIONS_VQ05=1/)
assert.match(pilot,/VITE_LUMIA_FACE_DIRECT_VQ051=1/)
assert.match(pilot,/ORBIA_LUMIA_VRM_GROUNDING_VQ03=1/)
assert.match(pilot,/INICIAR_LUMIA_ASUS_VISION_AUDITORIA_VI041\.cmd/)
assert.match(vision,/VITE_LUMIA_VISION_QA_VI041=1/)
assert.match(vision,/INICIAR_LUMIA_ASUS_ROSTROS_VI040A\.cmd/)
assert.match(read('INICIAR_LUMIA_ASUS_ROSTROS_VI040A.cmd'),/INICIAR_LUMIA_ASUS_VISION_REVISAR_VI032B\.cmd/)
assert.doesNotMatch(daily,/VITE_LUMIA_VISION_QA_VI041|VITE_LUMIA_FACE_DIRECT_VQ051/)
assert.match(app,/parseLumiaFaceActionVQ051\(said\)/)
assert.match(app,/auditFreshSceneAtTurn\(/)
assert.match(app,/VISION_SCENE_AUDIT_VI041_ENABLED/)
assert.match(app,/auditEnabled=\{VISION_SCENE_AUDIT_VI041_ENABLED\}/)
assert.match(app,/\[lumia:vision-vi041\]/)
assert.match(parser,/requestLumiaAvatarFaceVQ051/)
assert.match(face,/facePreview\.cue\(faceCmd\.preset\)/)
assert.match(vm,/auditEnabled/)
assert.match(voice,/auditNextCheckout\(/)
assert.match(voice,/NEXT_BRANCH='integration\/lumia-asus-next-20261114'/)
assert.match(voice,/makeVoiceQaChildEnv\(original\)/)
assert.match(voice,/LUMIA-NEXT-QA/)
assert.match(voice,/BASELINE_CHANGED/)
assert.match(voice,/NEXT_DIRTY/)
assert.match(voice,/INICIAR_LUMIA_ASUS_NEXT_QA\.cmd/)
assert.doesNotMatch(voice,/copyFileSync|writeFileSync|pip install|npm install|Set-ExecutionPolicy|git (reset|clean|checkout)/)
assert.doesNotMatch(pilot,/ollama pull|ollama rm|git reset|git checkout|getUserMedia/)
const asExpected=['VQ-04','VQ-05.1','VI-04.1']
for(const module of asExpected)assert.ok(manifest.carried_forward.some(x=>x.module===module))
console.log('LUMIA NEXT PASS: approved facial VRM and opt-in fresh-vision audit coexist in one QA launch, same Qwen 2B, protected original')

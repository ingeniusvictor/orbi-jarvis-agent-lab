import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {spawnSync} from 'node:child_process'
import {fileURLToPath} from 'node:url'
import {join} from 'node:path'

const root=fileURLToPath(new URL('../',import.meta.url))
const read=(p:string)=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const proc=spawnSync(process.execPath,['--import','tsx',join(root,'scripts/benchmark-lumia-amr029-config.ts')],{
  cwd:root,encoding:'utf8',timeout:20000
})
assert.equal(proc.status,0,proc.stderr)
const cfg=JSON.parse(proc.stdout)
assert.equal(cfg.model2B,'qwen3.5:2b')
assert.equal(cfg.model4B,'qwen3.5:4b-vision4096')
assert.equal(cfg.keepAlive,'5m')
assert.equal(cfg.options.num_ctx,4096)
assert.equal(cfg.options.temperature,0)
assert.equal(cfg.tasks.length,4)
assert.deepEqual(cfg.tasks.map((x:{id:string})=>x.id),['texto-simple','texto-razonamiento','voz-modelo','imagen'])
assert.deepEqual(cfg.tasks.map((x:{kind:string})=>x.kind),['written','written','speech-ready','image'])
assert.match(cfg.tasks[1].question,/8 A/)
assert.match(cfg.tasks[1].question,/10 A/)
assert.match(cfg.tasks[1].question,/segura/)
assert.match(cfg.voiceQuestion,/inversor fotovoltaico/)
assert.equal(cfg.tasks[2].question,cfg.voiceQuestion)
assert.match(cfg.visualQuestion,/personas visibles/)
assert.match(cfg.tasks[3].question,/revisa cada figura una sola vez/)
assert.match(cfg.tasks[3].question,/sin ambigüedades/)
assert.match(cfg.visualSystem,/Estás examinando una foto/)
assert.match(cfg.system,/L\.U\.M\.I\.A\./)
assert.equal(cfg.format.properties.respuesta.type,'string')
assert.equal(cfg.format.additionalProperties,false)
assert.doesNotMatch(proc.stdout,/data:image|base64|filePath|localStorage/)

const ps=read('scripts/benchmark-lumia-amr029-model-comparison.ps1')
assert.match(ps,/\[Parameter\(Mandatory=\$true\)\]\[string\]\$ImagePath/)
assert.match(ps,/\$Model2B='qwen3\.5:2b'/)
assert.match(ps,/\$Model4B='qwen3\.5:4b-vision4096'/)
assert.match(ps,/\[ValidateSet\(768,1024\)\]\[int\]\$Edge=768/)
assert.match(ps,/\$Model2B -eq \$Model4B/)
assert.match(ps,/\$inventory=@\(& ollama list\)/)
assert.match(ps,/\$Model2B=\$candidates\[0\]/)
assert.match(ps,/Hay varios modelos 2B/)
assert.match(ps,/No se encontró/)
assert.doesNotMatch(ps,/& ollama show \$model \*> \$null/)
assert.match(ps,/No se descargó ni modificó ningún modelo/)
assert.match(ps,/Quality, \[long\]76/)
assert.match(ps,/\$userMessage\.images=@\(\$frame\.data\)/)
assert.match(ps,/Invoke-RestMethod -Uri \$endpoint/)
assert.match(ps,/http:\/\/127\.0\.0\.1:11434\/api\/chat/)
assert.match(ps,/if \(\$task\.kind -eq 'speech-ready'\) \{\$payload\.format=\$cfg\.format\}/)
assert.match(ps,/prompt_eval_cached_count/)
assert.match(ps,/load_duration/)
assert.match(ps,/Fin='error'/)
assert.match(ps,/DIAGNÓSTICO DE CONVERSACIÓN/)
assert.match(ps,/Whisper, Kokoro y audio real/)
assert.doesNotMatch(ps,/ollama (?:pull|stop|rm|create)|Invoke-WebRequest|Out-File|Set-Content|Export-Csv|localStorage|GetUserMedia|JARVIS_ALLOW_WRITES=1/)
assert.doesNotMatch(ps,/https:\/\//)
const previous=read('scripts/benchmark-lumia-amr028-controlled.ps1')
assert.match(previous,/768,1024,1024,768/)
assert.match(read('INICIAR_LUMIA_ASUS_VISION_GRUPOS.cmd'),/INICIAR_LUMIA_ASUS_VISION_CONSISTENTE.cmd/)
const voice=read('bridge/ollama.mjs')
assert.match(voice,/format: responseSchema/)
assert.match(voice,/type: 'object'/)
assert.match(voice,/respuesta: \{ type: 'string' \}/)
console.log('AMR-02.9 PASS: canonical 2B/4B written + speech-response + image, no downloads, no user-file persistence and honest manual end-to-end voice verification')

import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {EphemeralVisualContext} from '../src/lib/vision-context-vi023'
import {MAX_VISUAL_FILE_BYTES,validateVisualFile} from '../src/lib/visual-input'

const read=(path:string)=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const app=read('src/App.tsx')
const panel=read('src/ui/LumiaCameraViewfinder.tsx')
const codec=read('src/lib/visual-input.ts')
const css=read('src/index.css')

for(const type of ['image/jpeg','image/png','image/webp'])
  assert.doesNotThrow(()=>validateVisualFile({type,size:1024}))
for(const type of ['image/gif','text/plain','application/pdf'])
  assert.throws(()=>validateVisualFile({type,size:1024}))
assert.throws(()=>validateVisualFile({type:'image/jpeg',size:MAX_VISUAL_FILE_BYTES+1}))
assert.throws(()=>validateVisualFile({type:'image/jpeg',size:0}))
assert.match(codec,/createImageBitmap\(file\)/)
assert.match(codec,/canvas\.toDataURL\('image\/jpeg'/)
assert.match(panel,/prepareVisualImage\(file,maxEdge\)/)
assert.match(panel,/type="file"/)
assert.match(panel,/onFileCaptured\(fileImage\)/)
assert.match(panel,/!fileImage\|\|fileBusy/)
assert.match(panel,/fileRequest\.current\+\+/)
assert.match(panel,/onSelectFileMode/)
assert.match(panel,/onSelectCameraMode/)
assert.match(panel,/Selecciona una imagen para previsualizarla/)
assert.match(panel,/No se activa la webcam/)
assert.match(panel,/Foto temporal · 5 minutos · se descarta al cerrar/)
assert.match(panel,/onAskAboutStill\(question\)/)
assert.match(app,/const \[visionFileMode,setVisionFileMode\]/)
assert.match(app,/const analyzeVisionFile = \(image:LocalVisualImage\)/)
assert.match(app,/onFileCaptured=\{analyzeVisionFile\}/)
assert.match(app,/setVisionStillSource\('file'\)/)
assert.match(app,/setCameraStill\(image\)/)
assert.match(app,/respond\('Lumi, describe exactamente lo que aparece en esta imagen y dime qué no puedes distinguir\.',image,false,true\)/)
assert.match(app,/visualSession\.current\.begin\(visualImage\)/)
assert.match(app,/visualSession\.current\.confirmAnalyzed\(visualGeneration\)/)
assert.match(app,/visualSession\.current\.getAuthorizedFrame\(\)/)
assert.match(app,/visualSession\.current\.clear\(\)/)
assert.match(app,/setVisionFileMode\(false\)/)
assert.match(app,/setCameraPreviewOpen\(!fileAgain\)/)
assert.match(app,/image && !fromCameraPreview && !cameraRequested/)
assert.match(app,/captureLumiaAuthorizedStill\(stale\)/)
assert.match(css,/\.lumia-vision-source-tabs/)
assert.match(css,/\.lumia-vision-file-controls/)
const session=new EphemeralVisualContext()
const image={mimeType:'image/jpeg' as const,data:'SIMULATED-JPEG'}
const ticket=session.begin(image,1000)
assert.equal(session.getAuthorizedFrame(1001),null)
assert.equal(session.confirmAnalyzed(ticket,1002),true)
assert.strictEqual(session.getAuthorizedFrame(1003)?.image,image)
session.clear()
assert.equal(session.getAuthorizedFrame(1004),null)
console.log('VISION-02.4 PASS: manual image picker validation, explicit send, same ephemeral photo conversation, camera isolation and existing VI-01 retained')

import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {createVisionTrace,visionTraceSummary,visionTracingEnabled,visualTraceIntent,visualPrecisionInstruction} from '../src/lib/vision-trace-amr026'
import {safeVisionTrace,explicitGroupCount,createVisionCountLedger} from '../bridge/orbia/vision-trace-amr026.mjs'
const read=(p:string)=>readFileSync(new URL('../'+p,import.meta.url),'utf8')

// Different JPEG preparations are independent random IDs, even for same size.
const a=createVisionTrace('camera',768,576,768,42000)
const b=createVisionTrace('camera',768,576,768,42000)
assert.match(a.photoId,/^p[a-zA-Z0-9-]{8,60}$/)
assert.notEqual(a.photoId,b.photoId)
assert.equal(a.source,'camera')
assert.equal(a.limitPx,768)
assert.match(visionTraceSummary(a),/source=camera edge=768px actual=576x768/)
assert.doesNotThrow(()=>createVisionTrace('file',512,400,512,2000000))
assert.throws(()=>createVisionTrace('file',512,0,512,120))
assert.throws(()=>createVisionTrace('file',512,512,512,2000001))
assert.equal(visionTracingEnabled(),false,'Default test environment must not auto-enable pilot')

assert.equal(visualTraceIntent('¿Cuántas personas aparecen?'),'count')
assert.equal(visualTraceIntent('Lumi, ¿qué letras puedes leer en mi camiseta?'),'ocr')
assert.equal(visualTraceIntent('Lumi, lee el número de serie de la etiqueta'),'ocr')
assert.equal(visualTraceIntent('Lumi, describe la fotografía y dime qué no distingues'),'scene')
assert.match(visualPrecisionInstruction('¿Cuántas personas aparecen?'),/una sola vez/)
assert.match(visualPrecisionInstruction('Lee la etiqueta'),/caracteres directamente visibles/)
assert.equal(visualPrecisionInstruction('Describe el fondo de esta foto'),'')

// Server accepts only metadata with bounded fields and exact JPEG size.
// Request IDs and photo IDs never come from filename, JPEG hash or prompt.
const raw={...a,turnId:'turn-0123456789',role:'followup' as const,intent:'count' as const}
assert.deepEqual(safeVisionTrace(raw,42000),raw)
assert.equal(safeVisionTrace({...raw,encodedChars:42001},42000),null)
assert.equal(safeVisionTrace({...raw,photoId:'../private.jpeg'},42000),null)
assert.equal(safeVisionTrace({...raw,intent:'private-file'},42000),null)
assert.equal(safeVisionTrace({...raw,width:2200},42000),null)
assert.equal(safeVisionTrace({...raw,role:'automatic-camera'},42000),null)
assert.equal(safeVisionTrace(undefined,42000),null)

// Only explicit group counts; no OCR voltages or data from a label.
assert.equal(explicitGroupCount('Veo ocho hombres al aire libre.'),8)
assert.equal(explicitGroupCount('Veo un grupo de ocho hombres.'),8)
assert.equal(explicitGroupCount('Hay siete figuras en total.'),7)
assert.equal(explicitGroupCount('Peligro 800 Volts.'),null)
assert.equal(explicitGroupCount('Hay una persona frente al marco.'),null)
const ledger=createVisionCountLedger()
assert.equal(ledger.review({photoId:a.photoId,answer:'Veo ocho hombres en grupo.',intent:'scene',now:1000}).status,'first')
assert.equal(ledger.review({photoId:a.photoId,answer:'Veo ocho hombres en la foto.',intent:'count',now:1001}).status,'consistent')
const mismatch=ledger.review({photoId:a.photoId,answer:'Hay siete figuras.',intent:'count',now:1002})
assert.equal(mismatch.status,'count-discrepancy')
assert.match(mismatch.text,/conteos diferentes/)
assert.doesNotMatch(mismatch.text,/\b(?:siete|ocho)\b/,'Do not falsely select a winner')
assert.equal(ledger.review({photoId:b.photoId,answer:'Hay siete personas.',intent:'count',now:1003}).status,'first')
assert.equal(ledger.review({photoId:a.photoId,answer:'Hay ocho personas.',intent:'scene',now:1004}).status,'changed-observation')
assert.equal(ledger.review({photoId:a.photoId,answer:'Hay ocho personas.',intent:'count',now:1000+300001}).status,'first','TTL expiry')
ledger.clear()
assert.equal(ledger.size,0)

// Only the explicitly opted-in launcher enables this feature.
const launcher=read('INICIAR_LUMIA_ASUS_VISION_TRAZA.cmd')
const previous=read('INICIAR_LUMIA_ASUS_VISION_CONTEXTUAL.cmd')
assert.match(launcher,/set "VITE_LUMIA_VISION_TRACE_AMR026=1"/)
assert.match(launcher,/set "ORBIA_LUMIA_VISUAL_QA_AMR026=1"/)
assert.match(launcher,/call "%~dp0INICIAR_LUMIA_ASUS_VISION_CONTEXTUAL.cmd"/)
assert.doesNotMatch(previous,/VITE_LUMIA_VISION_TRACE_AMR026=1/)
assert.doesNotMatch(launcher,/ollama\s+(?:rm|pull|create|stop)|num_gpu|num_batch/i)
const codec=read('src/lib/visual-input.ts')
const app=read('src/App.tsx')
const brain=read('src/lib/brain.ts')
const bridge=read('src/lib/bridge.ts')
const backend=read('bridge/ollama.mjs')
const validator=read('bridge/orbia/vision-trace-amr026.mjs')
assert.match(codec,/visionTracingEnabled\(\)\?createVisionTrace\('camera'/)
assert.match(codec,/visionTracingEnabled\(\)\?createVisionTrace\('file'/)
assert.match(codec,/\[lumia:vision-amr026\] prepared/)
assert.match(app,/visualImage=\{\.\.\.visualImage,trace:\{\.\.\.visualImage\.trace,turnId,role,intent:visualTraceIntent\(visualQuestion\)\}\}/)
assert.match(app,/\[lumia:vision-amr026\] turn/)
assert.match(app,/\[lumia:vision-amr026\] first-text/)
assert.match(bridge,/\[lumia:vision-amr026\] ws-send/)
assert.match(bridge,/ask=\$\{id\} turn=\$\{image\.trace\.turnId/)
assert.match(brain,/bridge\.ask\(prompt, handlers, image\)/)
assert.match(backend,/safeVisionTrace\(msg\.image\?\.trace,image\.data\.length\)/)
assert.match(backend,/visualTrace=image && process\.env\.ORBIA_LUMIA_VISUAL_QA_AMR026==='1'/)
assert.match(backend,/askId:ask/)
assert.match(backend,/visualLedger\.review/)
assert.match(backend,/const finalAnswer=typeof onVisualAnswer==='function'\?onVisualAnswer\(answer\):answer/)
assert.match(backend,/images: \[image\.data\]/)
assert.match(backend,/think: false/)
assert.match(backend,/doneReason=/)
assert.doesNotMatch(validator,/writeFile|localStorage|indexedDB|getUserMedia|toDataURL|crypto\.createHash/)
console.log('AMR-02.6 PASS: local opt-in trace, unique JPEG and turn identities, safe validation, TTL count guard, prompt intent isolation and unchanged Ollama image path')
